import fs from "node:fs/promises"
import os from "node:os"
import path from "node:path"
import { afterEach, beforeEach, describe, expect, it } from "vitest"
import type { CodegenResult } from "./codegen.js"
import { checkCodegenOutput, writeCodegenOutput } from "./output.js"

const HEADER = "// AUTO-GENERATED by @miragon/mcp-toolkit-tool-codegen. Do not edit by hand.\n"
const withHooks: CodegenResult = {
  toolsFile: `${HEADER}// tools\n`,
  hooksFile: `${HEADER}// hooks\n`,
  tools: [],
}
const withoutHooks: CodegenResult = { toolsFile: withHooks.toolsFile, tools: [] }

let dir: string
beforeEach(async () => {
  dir = await fs.mkdtemp(path.join(os.tmpdir(), "codegen-output-"))
})
afterEach(async () => {
  await fs.rm(dir, { recursive: true, force: true })
})

const read = (file: string) => fs.readFile(path.join(dir, file), "utf-8")
const exists = (file: string) =>
  fs.access(path.join(dir, file)).then(
    () => true,
    () => false,
  )

describe("writeCodegenOutput", () => {
  it("creates the directory and writes every generated file", async () => {
    const out = path.join(dir, "nested", "generated")
    expect(await writeCodegenOutput(withHooks, out)).toEqual({
      written: ["tools.ts", "hooks.tsx"],
      removed: [],
    })
    expect(await fs.readFile(path.join(out, "tools.ts"), "utf-8")).toBe(withHooks.toolsFile)
    expect(await fs.readFile(path.join(out, "hooks.tsx"), "utf-8")).toBe(withHooks.hooksFile)
  })

  it("removes the hooks.tsx it generated before once react is off", async () => {
    await writeCodegenOutput(withHooks, dir)
    expect(await writeCodegenOutput(withoutHooks, dir)).toEqual({
      written: ["tools.ts"],
      removed: ["hooks.tsx"],
    })
    expect(await exists("hooks.tsx")).toBe(false)
  })

  it("leaves a hooks.tsx alone that it did not generate", async () => {
    await fs.writeFile(path.join(dir, "hooks.tsx"), "export const mine = 1\n")
    expect((await writeCodegenOutput(withoutHooks, dir)).removed).toEqual([])
    expect(await read("hooks.tsx")).toBe("export const mine = 1\n")
  })

  it("resolves a relative directory against the working directory", async () => {
    const relative = path.relative(process.cwd(), path.join(dir, "rel"))
    await writeCodegenOutput(withoutHooks, relative)
    expect(await read("rel/tools.ts")).toBe(withoutHooks.toolsFile)
  })
})

describe("checkCodegenOutput", () => {
  it("reports nothing when the files match", async () => {
    await writeCodegenOutput(withHooks, dir)
    expect(await checkCodegenOutput(withHooks, dir)).toEqual([])
  })

  it("reports a missing and a changed file", async () => {
    await fs.writeFile(path.join(dir, "tools.ts"), "old\n")
    expect(await checkCodegenOutput(withHooks, dir)).toEqual([
      { file: "tools.ts", kind: "changed", expected: withHooks.toolsFile, actual: "old\n" },
      { file: "hooks.tsx", kind: "missing", expected: withHooks.hooksFile },
    ])
  })

  it("reports a generated hooks.tsx as stale when react is off, and writes nothing", async () => {
    await writeCodegenOutput(withHooks, dir)
    expect(await checkCodegenOutput(withoutHooks, dir)).toEqual([
      { file: "hooks.tsx", kind: "stale", actual: withHooks.hooksFile },
    ])
    expect(await read("hooks.tsx")).toBe(withHooks.hooksFile)
  })

  it("ignores a hooks.tsx it did not generate", async () => {
    await writeCodegenOutput(withoutHooks, dir)
    await fs.writeFile(path.join(dir, "hooks.tsx"), "export const mine = 1\n")
    expect(await checkCodegenOutput(withoutHooks, dir)).toEqual([])
  })

  // The header names the server's origin: generating from the same tools at another address (a
  // CI service host, another port) changes nothing the files hold.
  it("ignores the Source line of the header, and only that line", async () => {
    const generated = (source: string, body = "// tools\n") =>
      `${HEADER}// Regenerate with: mcp-tool-codegen generate\n// Source: ${source}\n${body}`
    const fresh: CodegenResult = { toolsFile: generated("http://localhost:4000"), tools: [] }
    await fs.writeFile(path.join(dir, "tools.ts"), generated("http://ci-service:4000"))
    expect(await checkCodegenOutput(fresh, dir)).toEqual([])

    for (const committed of [
      generated("http://ci-service:4000", "// tools changed\n"),
      generated("http://localhost:4000").replace("// Regenerate", "// Rebuild"),
      `${HEADER}// Source: http://localhost:4000\n// Regenerate with: mcp-tool-codegen generate\n// tools\n`,
      // A third line that is no Source line is compared like any other.
      generated("http://localhost:4000").replace("// Source: http://localhost:4000", "// Sauce: x"),
      generated("http://localhost:4000").replace("// tools\n", "// to\nols\n"),
    ]) {
      await fs.writeFile(path.join(dir, "tools.ts"), committed)
      expect(await checkCodegenOutput(fresh, dir)).toEqual([
        { file: "tools.ts", kind: "changed", expected: fresh.toolsFile, actual: committed },
      ])
    }
  })

  it("fails on a read error other than a missing file", async () => {
    await fs.mkdir(path.join(dir, "tools.ts"))
    await expect(checkCodegenOutput(withoutHooks, dir)).rejects.toThrow("EISDIR")
  })
})
