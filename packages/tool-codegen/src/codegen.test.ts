import { describe, expect, it } from "vitest"
import { renderCodegen } from "./codegen.js"
import type { CodegenConfig } from "./config.js"
import type { ToolDescriptor } from "./fetch-tools.js"
import { topLevelDeclarations, typeErrors } from "./test-support/typescript.js"

// Each test that runs typeErrors, a full TypeScript program, sets a 30 s timeout (see typeErrors).

const config: CodegenConfig = {
  name: "tasks",
  url: "http://localhost:3000/mcp",
  out: "src/generated",
  react: true,
}

const listTasks: ToolDescriptor = {
  name: "list_tasks",
  description: "Lists the tasks.",
  inputSchema: {
    type: "object",
    properties: { status: { type: "string", enum: ["open", "done"] } },
  },
  outputSchema: {
    type: "object",
    properties: { tasks: { type: "array", items: { type: "string" } } },
    required: ["tasks"],
  },
  annotations: { readOnlyHint: true },
}

const createTask: ToolDescriptor = {
  name: "create_task",
  description: "Creates a task.",
  inputSchema: {
    type: "object",
    properties: { title: { type: "string" } },
    required: ["title"],
  },
}

describe("renderCodegen: the generated files", () => {
  it("renders tools.ts: types, the tool map, and the typed client factory", async () => {
    const { toolsFile } = await renderCodegen([listTasks, createTask], config)
    expect(toolsFile)
      .toBe(`// AUTO-GENERATED by @miragon/mcp-toolkit-tool-codegen. Do not edit by hand.
// Regenerate with: mcp-tool-codegen generate
// Source: http://localhost:3000

import {
  createTypedCallTool,
  type ToolCallOptions,
  type ToolCaller,
  type TypedCallTool,
} from "@miragon/mcp-toolkit-tool-codegen-core"

export interface TasksCreateTaskInput {
  title: string
}

export type TasksCreateTaskOutput = unknown

export interface TasksListTasksInput {
  status?: "open" | "done"
}

export interface TasksListTasksOutput {
  tasks: string[]
}

export interface TasksToolMap {
  create_task: {
    input: TasksCreateTaskInput
    output: TasksCreateTaskOutput
  }
  list_tasks: {
    input: TasksListTasksInput
    output: TasksListTasksOutput
  }
}

export type TasksToolName = keyof TasksToolMap

export type TasksCallTool = TypedCallTool<TasksToolMap>

export function createTasksClient(callTool: ToolCaller) {
  const call = createTypedCallTool<TasksToolMap>(callTool)
  return {
    call,
    /** Creates a task. */
    createTask: (args: TasksCreateTaskInput, options?: ToolCallOptions) =>
      call("create_task", args, options),
    /** Lists the tasks. */
    listTasks: (args: TasksListTasksInput = {}, options?: ToolCallOptions) =>
      call("list_tasks", args, options),
  }
}

export type TasksClient = ReturnType<typeof createTasksClient>
`)
  })

  it("renders hooks.tsx: a query hook for the read-only tool, a mutation hook for the other", async () => {
    const { hooksFile } = await renderCodegen([listTasks, createTask], config)
    expect(hooksFile)
      .toBe(`// AUTO-GENERATED by @miragon/mcp-toolkit-tool-codegen. Do not edit by hand.
// Regenerate with: mcp-tool-codegen generate
// Source: http://localhost:3000

import {
  toolQueryKey,
  useToolMutation,
  useToolQuery,
  type ToolCallQueryKey,
  type UseToolMutationOptions,
  type UseToolQueryOptions,
} from "@miragon/mcp-toolkit-tool-codegen-react"
import type {
  TasksListTasksInput,
  TasksListTasksOutput,
  TasksToolMap,
  TasksToolName,
} from "./tools.js"

/** The key a query of this server caches a tool call under, for the QueryClient. */
export function tasksQueryKey<TName extends TasksToolName>(
  name: TName,
  args: TasksToolMap[TName]["input"],
): ToolCallQueryKey<TasksToolMap, TName> {
  return toolQueryKey<TasksToolMap, TName>("tasks", name, args)
}

/** Creates a task. */
export function useTasksCreateTaskMutation<TOnMutateResult = unknown>(
  options?: UseToolMutationOptions<TasksToolMap, "create_task", TOnMutateResult>,
) {
  return useToolMutation<TasksToolMap, "create_task", TOnMutateResult>(
    "tasks",
    "create_task",
    options,
  )
}

/** Lists the tasks. */
export function useTasksListTasksQuery<TSelected = TasksListTasksOutput>(
  args: TasksListTasksInput = {},
  options?: UseToolQueryOptions<TasksListTasksOutput, TSelected>,
) {
  return useToolQuery<TasksToolMap, "list_tasks", TSelected>("tasks", "list_tasks", args, options)
}
`)
  })

  it("type-checks against the runtime packages and rejects unknown tools and wrong args", async () => {
    const { toolsFile, hooksFile = "" } = await renderCodegen([listTasks, createTask], config)
    const consumer = `
import type { ToolQueryContext } from "@miragon/mcp-toolkit-tool-codegen-react"
import { createTasksClient, type TasksClient, type TasksToolName } from "./tools.js"
import { tasksQueryKey, useTasksCreateTaskMutation, useTasksListTasksQuery } from "./hooks.js"

declare const callTool: import("@miragon/mcp-toolkit-tool-codegen-core").ToolCaller
const client: TasksClient = createTasksClient(callTool)
export const names: TasksToolName[] = ["create_task", "list_tasks"]

export async function use() {
  const created: unknown = await client.createTask({ title: "Write docs" })
  const listed: string[] = (await client.listTasks()).tasks
  const viaCall: string[] = (await client.call("list_tasks", { status: "open" })).tasks
  // @ts-expect-error -- the map has no index signature: an unknown tool name does not compile
  await client.call("list_task", {})
  // @ts-expect-error -- a required argument is missing
  await client.createTask({})
  // @ts-expect-error -- a wrong argument value
  await client.listTasks({ status: "closed" })
  // @ts-expect-error -- not a tool of the map
  const wrongName: TasksToolName = "delete_task"
  const count: number | undefined = useTasksListTasksQuery({}, { select: (data) => data.tasks.length }).data
  useTasksCreateTaskMutation({ onSuccess: (data) => void data }).mutate({ title: "Ship it" })
  return [created, listed, viaCall, wrongName, count]
}

export function useCache(queryClient: ToolQueryContext["queryClient"]) {
  const listed: { tasks: string[] } | undefined = queryClient.getQueryData(tasksQueryKey("list_tasks", {}))
  // @ts-expect-error -- a cache key names a tool of the map
  tasksQueryKey("list_task", {})
  // @ts-expect-error -- and takes its input
  tasksQueryKey("list_tasks", { status: "closed" })
  const create = useTasksCreateTaskMutation({
    onMutate: () => ({ before: listed }),
    onError: (_error, _args, context) => queryClient.setQueryData(tasksQueryKey("list_tasks", {}), context?.before),
    // @ts-expect-error -- an invalidation prefix names a tool of the map
    invalidates: [["tasks", "list-tasks"]],
  })
  return create
}
`
    expect(
      typeErrors({ "tools.ts": toolsFile, "hooks.tsx": hooksFile, "consumer.ts": consumer }),
    ).toEqual([])
  }, 30_000)

  it("leaves hooks.tsx out unless react is on", async () => {
    const result = await renderCodegen([listTasks], { ...config, react: undefined })
    expect(result.hooksFile).toBeUndefined()
    expect(result.toolsFile).not.toContain("react")
  })

  it("keys the tool map by the server's own tool names, unprefixed", async () => {
    const { toolsFile } = await renderCodegen(
      [{ name: "get-task", inputSchema: { type: "object" } }],
      { ...config, name: "billing-api" },
    )
    expect(toolsFile).toContain(`  "get-task": {\n    input: BillingApiGetTaskInput\n`)
    expect(toolsFile).toContain(
      `getTask: (args: BillingApiGetTaskInput = {}, options?: ToolCallOptions) =>`,
    )
    expect(toolsFile).not.toContain("billing-api_")
  })

  it("sorts by tool name in code-unit order and returns the tools sorted", async () => {
    const tools = ["b", "B", "a", "_z"].map((name) => ({ name: `t${name}`, inputSchema: {} }))
    const result = await renderCodegen(tools, { ...config, react: false })
    expect(result.tools.map((tool) => tool.name)).toEqual(["tB", "t_z", "ta", "tb"])
  })

  it("renders a server without tools", async () => {
    const { toolsFile, hooksFile = "" } = await renderCodegen([], config)
    expect(toolsFile).toContain("export interface TasksToolMap {}\n")
    expect(toolsFile).not.toContain("ToolCallOptions")
    expect(hooksFile.endsWith("\n\nexport {}\n")).toBe(true)
    expect(typeErrors({ "tools.ts": toolsFile, "hooks.tsx": hooksFile })).toEqual([])
  }, 30_000)
})

describe("renderCodegen: types", () => {
  it("types a tool without outputSchema as unknown, and an empty object as Record<string, never>", async () => {
    const { toolsFile } = await renderCodegen(
      [{ name: "ping", inputSchema: { type: "object", properties: {}, description: "No input." } }],
      config,
    )
    expect(toolsFile).toContain(
      "/** No input. */\nexport type TasksPingInput = Record<string, never>\n\nexport type TasksPingOutput = unknown\n",
    )
  })

  it("prefixes the types it declares for $defs and $ref targets with the tool's type name", async () => {
    const shared = {
      type: "object",
      properties: { address: { $ref: "#/$defs/Address" }, status: { $ref: "#/$defs/Status" } },
      $defs: {
        Address: { type: "object", properties: { city: { type: "string" } } },
        Status: { type: "string", enum: ["open", "done"] },
      },
    }
    const { toolsFile } = await renderCodegen(
      [
        { name: "create_order", inputSchema: shared },
        { name: "update_order", inputSchema: shared },
      ],
      config,
    )
    expect(topLevelDeclarations(toolsFile, "tools.ts")).toEqual([
      "TasksCreateOrderInputStatus",
      "TasksCreateOrderInput",
      "TasksCreateOrderInputAddress",
      "TasksCreateOrderOutput",
      "TasksUpdateOrderInputStatus",
      "TasksUpdateOrderInput",
      "TasksUpdateOrderInputAddress",
      "TasksUpdateOrderOutput",
      "TasksToolMap",
      "TasksToolName",
      "TasksCallTool",
      "createTasksClient",
      "TasksClient",
    ])
  })

  it("types only a plain object schema without properties as Record<string, never>", async () => {
    const schemas: [Record<string, unknown>, string][] = [
      [{ type: "object" }, "export type TasksAInput = Record<string, never>"],
      [
        { type: "object", properties: {}, required: [], additionalProperties: false },
        "export type TasksAInput = Record<string, never>",
      ],
      [
        { type: "object", additionalProperties: true },
        "export interface TasksAInput {\n  [k: string]: unknown\n}",
      ],
      [
        { type: "object", additionalProperties: { type: "number" } },
        "export interface TasksAInput {\n  [k: string]: number\n}",
      ],
      [{ type: "object", required: ["x"] }, "export interface TasksAInput {\n  x: unknown\n}"],
      [{ properties: {} }, "export interface TasksAInput {}"],
      [
        { type: "object", properties: {}, anyOf: [{ type: "object" }] },
        "export type TasksAInput = {}",
      ],
    ]
    for (const [inputSchema, declaration] of schemas) {
      const { toolsFile } = await renderCodegen([{ name: "a", inputSchema }], config)
      expect(toolsFile, JSON.stringify(inputSchema)).toContain(`\n${declaration}\n`)
    }
  })

  // For an output, an object schema without properties means any object, not an empty one.
  it("types an output object without properties as Record<string, unknown>, unless closed", async () => {
    const outputs: [Record<string, unknown>, string][] = [
      [{ type: "object" }, "export type TasksAOutput = Record<string, unknown>"],
      [{ type: "object", properties: {} }, "export type TasksAOutput = Record<string, unknown>"],
      [
        { type: "object", additionalProperties: false },
        "export type TasksAOutput = Record<string, never>",
      ],
      [{ type: "object", required: ["id"] }, "export interface TasksAOutput {\n  id: unknown\n}"],
    ]
    for (const [outputSchema, declaration] of outputs) {
      const { toolsFile } = await renderCodegen(
        [{ name: "a", inputSchema: { type: "object" }, outputSchema }],
        config,
      )
      expect(toolsFile, JSON.stringify(outputSchema)).toContain(`\n${declaration}\n`)
    }
  })

  it("rejects what an object input with required names but no properties does not accept", async () => {
    const { toolsFile } = await renderCodegen(
      [
        { name: "a", inputSchema: { type: "object", required: ["id"] } },
        { name: "b", inputSchema: { type: "object" }, outputSchema: { type: "object" } },
      ],
      { ...config, react: false },
    )
    const consumer = `
import { createTasksClient } from "./tools.js"
declare const callTool: import("@miragon/mcp-toolkit-tool-codegen-core").ToolCaller
const client = createTasksClient(callTool)
export async function use() {
  await client.a({ id: 1 })
  // @ts-expect-error -- not an object with an id
  await client.a(42)
  const id: unknown = (await client.b()).id
  return id
}
`
    expect(typeErrors({ "tools.ts": toolsFile, "consumer.ts": consumer })).toEqual([])
  }, 30_000)

  it("requires args unless {} is a valid input", async () => {
    const tool = (name: string, inputSchema: Record<string, unknown>): ToolDescriptor => ({
      name,
      inputSchema,
    })
    const { toolsFile } = await renderCodegen(
      [
        tool("a_required", {
          type: "object",
          properties: { x: { type: "string" } },
          required: ["x"],
        }),
        tool("b_optional", { type: "object", properties: { x: { type: "string" } } }),
        tool("c_composed", { type: "object", anyOf: [{ required: ["x"] }] }),
        tool("d_untyped", { properties: { x: { type: "string" } } }),
        tool("e_flagged", {
          type: "object",
          properties: { x: { type: "string", required: true } },
        }),
        tool("f_empty", { type: "object", properties: { x: { type: "string" } }, required: [] }),
        tool("g_ref", { type: "object", $ref: "#/$defs/G", $defs: { G: { type: "object" } } }),
        tool("h_all", { type: "object", allOf: [{ type: "object" }] }),
        tool("i_one", { type: "object", oneOf: [{ type: "object" }] }),
        tool("j_plain", { type: "object", properties: { x: { type: "string", required: false } } }),
        tool("k_boolean", { type: "object", properties: { x: true } }),
      ],
      { ...config, react: false },
    )
    expect(toolsFile).toContain("aRequired: (args: TasksARequiredInput, options")
    expect(toolsFile).toContain("bOptional: (args: TasksBOptionalInput = {}, options")
    expect(toolsFile).toContain("cComposed: (args: TasksCComposedInput, options")
    expect(toolsFile).toContain("dUntyped: (args: TasksDUntypedInput, options")
    expect(toolsFile).toContain("eFlagged: (args: TasksEFlaggedInput, options")
    expect(toolsFile).toContain("fEmpty: (args: TasksFEmptyInput = {}, options")
    expect(toolsFile).toContain("gRef: (args: TasksGRefInput, options")
    expect(toolsFile).toContain("hAll: (args: TasksHAllInput, options")
    expect(toolsFile).toContain("iOne: (args: TasksIOneInput, options")
    expect(toolsFile).toContain("jPlain: (args: TasksJPlainInput = {}, options")
    expect(toolsFile).toContain("kBoolean: (args: TasksKBooleanInput = {}, options")
  })

  // `{}` carries the members TypeScript gives every object, so it is no valid default for an
  // input with an optional property of that name (or json2ts would read draft 3's required flag
  // on a $ref's target, which the default must see too).
  it("requires args when {} would not type-check: object member names, draft 3 flags behind $ref", async () => {
    const tools: ToolDescriptor[] = [
      ...["constructor", "toString", "valueOf", "isPrototypeOf", "toLocaleString"].map(
        (member) => ({
          name: `member_${member}`,
          inputSchema: { type: "object", properties: { [member]: { type: "string" } } },
        }),
      ),
      {
        name: "flag_behind_ref",
        inputSchema: {
          type: "object",
          properties: { a: { $ref: "#/$defs/A" } },
          $defs: { A: { type: "string", required: true } },
        },
      },
      {
        name: "flag_on_root",
        inputSchema: { type: "object", required: true, properties: { self: { $ref: "#" } } },
      },
      {
        name: "plain_ref",
        inputSchema: {
          type: "object",
          properties: { a: { $ref: "#/$defs/A" } },
          $defs: { A: { type: "string" } },
        },
      },
    ]
    const { toolsFile } = await renderCodegen(tools, { ...config, react: false })
    for (const member of [
      "Constructor",
      "ToString",
      "ValueOf",
      "IsPrototypeOf",
      "ToLocaleString",
    ]) {
      expect(toolsFile).toContain(`(args: TasksMember${member}Input, options`)
    }
    expect(toolsFile).toContain("(args: TasksFlagBehindRefInput, options")
    expect(toolsFile).toContain("(args: TasksFlagOnRootInput, options")
    expect(toolsFile).toContain("(args: TasksPlainRefInput = {}, options")
    expect(typeErrors({ "tools.ts": toolsFile })).toEqual([])
  }, 30_000)

  it("names a json2ts failure after the tool and the override that avoids it", async () => {
    // json2ts calls schema.hasOwnProperty on the properties map, which this key replaces.
    await expect(
      renderCodegen(
        [{ name: "odd", inputSchema: { type: "object", properties: { hasOwnProperty: {} } } }],
        config,
      ),
    ).rejects.toThrow(
      /^cannot generate the input type of the tool "odd": .+\. Set overrides\["odd"\]\.input to a TypeScript type to skip its schema\.$/,
    )
    await expect(
      renderCodegen(
        [{ name: "odd", inputSchema: { type: "object", properties: { hasOwnProperty: {} } } }],
        config,
      ),
    ).rejects.toMatchObject({ cause: expect.any(TypeError) as unknown })
  })
})

describe("renderCodegen: hooks follow readOnlyHint", () => {
  const tool = (name: string, annotations?: ToolDescriptor["annotations"]): ToolDescriptor => ({
    name,
    inputSchema: { type: "object" },
    ...(annotations ? { annotations } : {}),
  })

  async function hookNames(tools: ToolDescriptor[], overrides?: CodegenConfig["overrides"]) {
    const { hooksFile = "" } = await renderCodegen(tools, { ...config, overrides })
    return topLevelDeclarations(hooksFile, "hooks.tsx").filter((name) => name.startsWith("use"))
  }

  it("gives a query hook only to a tool annotated readOnlyHint: true", async () => {
    expect(
      await hookNames([
        tool("reads", { readOnlyHint: true }),
        tool("unannotated"),
        tool("writes", { readOnlyHint: false }),
        tool("idempotent", { idempotentHint: true, destructiveHint: false }),
      ]),
    ).toEqual([
      "useTasksIdempotentMutation",
      "useTasksReadsQuery",
      "useTasksUnannotatedMutation",
      "useTasksWritesMutation",
    ])
  })

  it("lets an override force the hook kind either way", async () => {
    expect(
      await hookNames([tool("reads", { readOnlyHint: true }), tool("search")], {
        reads: { hook: "mutation" },
        search: { hook: "query" },
      }),
    ).toEqual(["useTasksReadsMutation", "useTasksSearchQuery"])
  })

  it("imports only the hook kinds it uses, and writes the query-key helper only for queries", async () => {
    const { hooksFile = "" } = await renderCodegen([tool("writes")], config)
    expect(hooksFile).toContain(
      `import {\n  useToolMutation,\n  type UseToolMutationOptions,\n} from "@miragon/mcp-toolkit-tool-codegen-react"\nimport type { TasksToolMap } from "./tools.js"\n`,
    )
    expect(hooksFile).not.toContain("QueryKey")
  })

  it("fails when the query-key helper would shadow an import", async () => {
    await expect(
      renderCodegen([tool("reads", { readOnlyHint: true })], { ...config, name: "tool" }),
    ).rejects.toThrow(
      `cannot generate hooks.tsx: the import toolQueryKey and the config name "tool" both produce the identifier "toolQueryKey". Change the config name.`,
    )
  })
})

describe("renderCodegen: overrides", () => {
  it("replaces the input and output types and makes args required", async () => {
    const { toolsFile } = await renderCodegen([{ ...listTasks, outputSchema: undefined }], {
      ...config,
      overrides: {
        list_tasks: { input: "{ status?: string }", output: " Array<{ id: string }> " },
      },
    })
    expect(toolsFile).toContain("export type TasksListTasksInput = { status?: string }\n")
    expect(toolsFile).toContain("export type TasksListTasksOutput = Array<{ id: string }>\n")
    expect(toolsFile).toContain("listTasks: (args: TasksListTasksInput, options")
  })

  it("takes the identifiers of a tool from its identifier override", async () => {
    const { toolsFile, hooksFile = "" } = await renderCodegen(
      [
        { ...listTasks, name: "then" },
        { ...createTask, name: "工具" },
      ],
      {
        ...config,
        overrides: { then: { identifier: "listAll" }, 工具: { identifier: "addTask" } },
      },
    )
    expect(toolsFile).toContain("export interface TasksListAllInput {")
    expect(toolsFile).toContain(
      `listAll: (args: TasksListAllInput = {}, options?: ToolCallOptions) =>\n      call("then", args, options),`,
    )
    expect(toolsFile).toContain(`  "工具": {\n    input: TasksAddTaskInput\n`)
    expect(topLevelDeclarations(hooksFile, "hooks.tsx")).toEqual([
      "tasksQueryKey",
      "useTasksListAllQuery",
      "useTasksAddTaskMutation",
    ])
    expect(typeErrors({ "tools.ts": toolsFile, "hooks.tsx": hooksFile })).toEqual([])
  }, 30_000)

  it("fails on overrides for tools the server does not list, naming them", async () => {
    await expect(
      renderCodegen([listTasks], {
        ...config,
        overrides: { list_task: { output: "string" }, list_tasks: {}, lst: { hook: "query" } },
      }),
    ).rejects.toThrow(`"overrides" names tools the server does not list: "list_task", "lst"`)
  })
})

describe("renderCodegen: rejects", () => {
  it("an invalid config, before rendering anything", async () => {
    await expect(renderCodegen([listTasks], { ...config, name: "1tasks" })).rejects.toThrow(
      `"name" must start with a letter`,
    )
  })

  it("a tool listed twice", async () => {
    await expect(renderCodegen([listTasks, listTasks], config)).rejects.toThrow(
      `the server lists the tool "list_tasks" twice`,
    )
  })

  it("a tool without a string name", async () => {
    await expect(
      renderCodegen([{ inputSchema: {} } as unknown as ToolDescriptor], config),
    ).rejects.toThrow("the server lists a tool without a name")
  })
})
