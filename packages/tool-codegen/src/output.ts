import fs from "node:fs/promises"
import path from "node:path"
import type { CodegenResult } from "./codegen.js"

export type CodegenFile = "tools.ts" | "hooks.tsx"

/** One way the files in an output directory differ from a fresh generation. */
export interface CodegenDrift {
  file: CodegenFile
  /**
   * `missing`: the file should exist but does not. `changed`: its content
   * differs. `stale`: a generated `hooks.tsx` is left over although `react` is off.
   */
  kind: "missing" | "changed" | "stale"
  /** The freshly generated content (`missing`, `changed`). */
  expected?: string
  /** The content on disk (`changed`, `stale`). */
  actual?: string
}

/** The first line of every generated file; marks a file as the generator's own. */
const GENERATED_MARKER = "// AUTO-GENERATED by @miragon/mcp-toolkit-tool-codegen."

const SOURCE_LINE = "// Source:"

/**
 * The file without the server's origin in its third line: it says where the
 * files were generated from, not what they hold, so a check against the same
 * tools at another address (a CI service host, another port) is no drift.
 */
function withoutSource(content: string): string {
  const lines = content.split("\n")
  if (lines[2]?.startsWith(`${SOURCE_LINE} `)) lines[2] = SOURCE_LINE
  return lines.join("\n")
}

function expectedFiles(result: CodegenResult): [CodegenFile, string][] {
  const files: [CodegenFile, string][] = [["tools.ts", result.toolsFile]]
  if (result.hooksFile !== undefined) files.push(["hooks.tsx", result.hooksFile])
  return files
}

async function readIfExists(file: string): Promise<string | undefined> {
  try {
    return await fs.readFile(file, "utf-8")
  } catch (error) {
    if ((error as NodeJS.ErrnoException).code === "ENOENT") return undefined
    throw error
  }
}

/** A `hooks.tsx` the generator wrote earlier, now that `react` is off. */
async function staleHooks(result: CodegenResult, dir: string): Promise<string | undefined> {
  if (result.hooksFile !== undefined) return undefined
  const content = await readIfExists(path.join(dir, "hooks.tsx"))
  return content?.startsWith(GENERATED_MARKER) ? content : undefined
}

/**
 * Writes the generated files into `outDir` (created if needed; a relative
 * path resolves against the working directory) and removes a `hooks.tsx` the
 * generator wrote earlier when the result has none (`react` turned off).
 */
export async function writeCodegenOutput(
  result: CodegenResult,
  outDir: string,
): Promise<{ written: CodegenFile[]; removed: CodegenFile[] }> {
  const dir = path.resolve(outDir)
  await fs.mkdir(dir, { recursive: true })
  const files = expectedFiles(result)
  await Promise.all(files.map(([file, content]) => fs.writeFile(path.join(dir, file), content)))
  const removed: CodegenFile[] = []
  if ((await staleHooks(result, dir)) !== undefined) {
    await fs.rm(path.join(dir, "hooks.tsx"))
    removed.push("hooks.tsx")
  }
  return { written: files.map(([file]) => file), removed }
}

/**
 * Compares `outDir` with a fresh generation without writing anything; an
 * empty list means the committed files are up to date. The `// Source:`
 * header line is not compared.
 */
export async function checkCodegenOutput(
  result: CodegenResult,
  outDir: string,
): Promise<CodegenDrift[]> {
  const dir = path.resolve(outDir)
  const drift: CodegenDrift[] = []
  for (const [file, expected] of expectedFiles(result)) {
    const actual = await readIfExists(path.join(dir, file))
    if (actual === undefined) drift.push({ file, kind: "missing", expected })
    else if (withoutSource(actual) !== withoutSource(expected)) {
      drift.push({ file, kind: "changed", expected, actual })
    }
  }
  const stale = await staleHooks(result, dir)
  if (stale !== undefined) drift.push({ file: "hooks.tsx", kind: "stale", actual: stale })
  return drift
}
